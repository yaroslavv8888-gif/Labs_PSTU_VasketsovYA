#include <iostream>
using namespace std;
#include <clocale>
#include <cstdlib>

int main()
{
    setlocale(LC_ALL, ".UTF8");
    const int N = 100;
    int mas[N]; // объявляем первый массив на 100 элементов

    cout << "1) Массив = ";
    for(int i = 0; i < N; ++i)
    {
        mas[i] = rand() % 100 - 50; // записываем случайные числа от -50 до 49
        cout << "[" << mas[i] << "] ";
    }
    cout << endl;

    int mas1[N] = {}; // объявляем второй массив
    cout << endl << "2) Массив после удаления элементов с индексами кратными 3 = ";
    int cot = 0; // счетчик элементов второго массива

    for(int i = 0; i < N; ++i)
    {
        if(i % 3 != 0) // сохраняем элементы с индексами не кратными 3
        {
            mas1[cot] = mas[i]; // записываем подряд без пропусков
            cout << "[" << mas1[cot] << "] ";
            cot++;
        }
    }
    cout << endl;
    cout << endl;

    cout << "3) Массив после добавления элементов со значением |M[i-1]+1| = ";
    int mas2[2*N] = {}; // объявляем третий массив с запасом места
    int cot1 = 0; // счетчик элементов третьего массива

    for(int i = 0; i < cot; ++i) // перебираем заполненную часть второго массива
    {
        mas2[cot1] = mas1[i]; // копируем каждый элемент в третий массив
        cot1++;

        if(mas1[i] < 0 && i > 0) // проверяем знак и наличие предыдущего элемента
        {
            // при i = 0 формулу не считаем чтобы не обращаться к mas1[-1]
            int m = abs(mas1[i - 1] + 1); // прибавляем 1 к предыдущему элементу и берем модуль
            mas2[cot1] = m; // записываем результат после отрицательного элемента
            cot1++;
        }
    }

    for(int j = 0; j < cot1; ++j) // выводим только записанные элементы
    {
        cout << "[" << mas2[j] << "] ";
    }

    return 0;
}